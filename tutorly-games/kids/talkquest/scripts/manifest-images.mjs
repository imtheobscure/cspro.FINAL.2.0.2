#!/usr/bin/env node
/**
 * Write `src/lib/imageManifest.ts` — which hand-made artwork files actually exist.
 *
 * Why this exists
 * ---------------
 * Every game backdrop prefers its real picture (`public/images/whisper-wall.jpg`)
 * and only falls back to the generated `.svg` scene. Without knowing what is on
 * disk, the browser discovers that by TRYING: five extensions × twenty-odd images
 * is a hundred 404s before the first paint, on a tablet, on a school connection.
 *
 * So the build looks in `public/images/` once and records what is there. `scene()`
 * then returns the real file when it exists and the `.svg` when it does not — the
 * usual zero wasted requests — while `SceneImageGuard` stays mounted as the safety
 * net for a file added after the build.
 *
 * Runs from `npm run build` before `next build`, so dropping new artwork in and
 * rebuilding is all it takes. Never edit the generated file by hand.
 *
 * Usage: node scripts/manifest-images.mjs
 */
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const imagesDir = path.join(root, "public", "images");
const outFile = path.join(root, "src", "lib", "imageManifest.ts");

/** Raster extensions that count as hand-made artwork, in preference order. */
const EXTENSIONS = ["jpg", "jpeg", "png", "webp", "avif"];

let entries = [];
try {
  entries = await readdir(imagesDir, { withFileTypes: true });
} catch {
  console.warn(`[manifest-images] no ${path.relative(root, imagesDir)}/ — the generated scenes will be used`);
}

/** name → the extension of the real artwork for that game. */
const artwork = {};
for (const entry of entries) {
  if (!entry.isFile()) continue;
  const ext = path.extname(entry.name).slice(1).toLowerCase();
  if (!EXTENSIONS.includes(ext)) continue;
  const name = path.basename(entry.name, path.extname(entry.name));
  // First extension in preference order wins, so a stray .png copy can never
  // shadow the .jpg the tutor meant to use.
  if (!artwork[name] || EXTENSIONS.indexOf(ext) < EXTENSIONS.indexOf(artwork[name])) {
    artwork[name] = ext;
  }
}

const body = `/**
 * GENERATED by scripts/manifest-images.mjs — do not edit.
 *
 * The hand-made artwork found in \`public/images/\` at build time. Regenerate with
 * \`npm run build\` (or \`node scripts/manifest-images.mjs\`).
 */
export const IMAGE_MANIFEST: Record<string, string> = ${JSON.stringify(artwork, null, 2)};
`;

await writeFile(outFile, body, "utf8");

const names = Object.keys(artwork);
console.log(
  `[manifest-images] ${names.length} artwork file(s) found${names.length ? `: ${names.join(", ")}` : ""}`,
);
console.log(
  names.length
    ? `[manifest-images] wrote ${path.relative(root, outFile)}`
    : "[manifest-images] wrote an empty manifest — every scene will use its generated .svg until artwork is added",
);
