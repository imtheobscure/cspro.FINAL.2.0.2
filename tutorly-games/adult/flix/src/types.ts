/**
 * Flix domain types.
 *
 * Three layers, deliberately decoupled by these shapes:
 *   1. MEDIA      — sources, tracks, streaming engines, playback state
 *   2. SUBTITLES  — a unified cue/word model every parser normalises into
 *   3. LESSON     — segments + timestamped activities, plus the AI pack schema
 *
 * The lesson schema is the SAME one the existing Video-Lesson app's Master
 * Prompt produces (`metadata` / `segments[].activities[]`), so a pack generated
 * for either app works in both. Flix only ADDS optional fields
 * (word-level timings, speakers, media sources) and never renames a key.
 */

/* ─────────────────────────────── MEDIA ─────────────────────────────── */

export type MediaKind = "hls" | "dash" | "progressive" | "youtube" | "dailymotion" | "vimeo" | "local";

/** How a source is authorised — only these four are ever playable. */
export type SourceLicence =
  | "owned"
  | "licensed"
  | "public-domain"
  | "creative-commons"
  | "official-embed";

export interface MediaSource {
  id: string;
  url: string;
  kind: MediaKind;
  /** Higher wins when several candidates for one episode exist. */
  quality: number;
  licence: SourceLicence;
  /** Human label shown in the source menu ("main", "backup CDN", …). */
  label: string;
  /** Attribution shown under the player for CC / public-domain material. */
  attribution?: string;
}

export interface MediaTrack {
  id: string;
  kind: "audio" | "text";
  label: string;
  language: string;
  /** Text tracks only: the parsed cues. */
  cues?: SubtitleCue[];
  /** Text tracks only: raw file (so it can be re-exported / sent to the AI). */
  raw?: string;
  format?: SubtitleFormat;
  /** "original" = the language being taught, "translation" = learner L1. */
  role: "original" | "translation";
  cc?: boolean;
  forced?: boolean;
}

export type SubtitleFormat = "vtt" | "srt" | "ass" | "ssa" | "json" | "text";

/** The playback state that must survive a source fallback, untouched. */
export interface PreservedPlayback {
  time: number;
  paused: boolean;
  rate: number;
  audioTrackId: string | null;
  textTrackId: string | null;
  volume: number;
  muted: boolean;
}

export interface Episode {
  id: string;
  title: string;
  show: string;
  season?: number;
  episodeNumber?: number;
  description: string;
  cefrLevel: string;
  targetLanguage: string;
  poster?: string;
  durationSeconds: number;
  sources: MediaSource[];
  tracks: MediaTrack[];
  /** Timed thumbnails + waveform generated by the media processor. */
  thumbnails?: { time: number; dataUrl: string }[];
  waveform?: number[];
  lessonId?: string;
  createdAt: number;
}

/* ───────────────────────────── SUBTITLES ───────────────────────────── */

/** A single word with its own timing (WhisperX-style word-level alignment). */
export interface SubtitleWord {
  text: string;
  startTime: number;
  endTime: number;
  /** Confidence 0–1 when the aligner provided one. */
  confidence?: number;
  /** Index of the speaker in the cue's `speakers` list. */
  speaker?: number;
}

export interface SubtitleCue {
  id: string;
  startTime: number;
  endTime: number;
  text: string;
  /** Word-level timings; falls back to even distribution when absent. */
  words?: SubtitleWord[];
  /** Speaker diarisation label ("SPEAKER_1" / "Narrator" / a learner's name). */
  speaker?: string;
  translation?: string;
  /** Line breaks the subtitle author intended, preserved for display. */
  lines?: string[];
}

export type SubtitleMode = "off" | "original" | "translation" | "dual";

export interface SubtitleTrackPair {
  original: MediaTrack | null;
  translation: MediaTrack | null;
}

/* ────────────────────────────── LESSON ─────────────────────────────── */

export type ActivityType =
  | "flashcard"
  | "multipleChoice"
  | "trueFalse"
  | "fillBlanks"
  | "dragDrop"
  | "matching"
  | "speaking"
  | "discussion"
  | "ordering"
  | "wordScramble"
  | "reflection"
  | "hotspot"
  | "videoPause"
  | "readingChallenge"
  | "listeningComprehension";

export type ActivityColor = "gold" | "teal" | "purple" | "orange" | "green" | "pink" | "blue";
export type Difficulty = "easy" | "medium" | "hard";

export interface ActivityOption {
  id: string;
  text: string;
  isCorrect?: boolean;
}

export interface MatchPair {
  left: string;
  right: string;
}

export interface LessonCard {
  front: string;
  back: string;
  example?: string;
  pronunciation?: string;
  translation?: string;
}

export interface ReadingContent {
  title: string;
  genre: "fiction" | "factual" | "whatIf";
  text: string;
  translation?: string;
  questions: { question: string; options: ActivityOption[]; explanation?: string }[];
}

export interface ListeningContent {
  title: string;
  genre: "podcast" | "dialogue" | "talk" | "interview" | "story";
  audioText: string;
  translation?: string;
  showTranscript: boolean;
  questions: { question: string; options: ActivityOption[]; timestamp?: number }[];
}

export interface HotspotContent {
  x: number;
  y: number;
  question: string;
  options?: ActivityOption[];
  hint?: string;
}

export interface ActivityContent {
  question?: string;
  term?: string;
  definition?: string;
  example?: string;
  pronunciation?: string;
  translation?: string;
  options?: ActivityOption[];
  answer?: boolean;
  sentence?: string;
  blanks?: string[];
  items?: string[];
  targets?: string[];
  pairs?: MatchPair[];
  expectedSentence?: string;
  discussionPrompt?: string;
  hotspot?: HotspotContent;
  videoPausePrompt?: string;
  reading?: ReadingContent;
  listening?: ListeningContent;
  cards?: LessonCard[];
  scrambledWord?: string;
  correctWord?: string;
  orderedItems?: string[];
  reflectionPrompt?: string;
  /** Optional WhisperX sentence id this activity was built from. */
  cueId?: string;
}

export interface ActivityFeedback {
  correctFeedback: string;
  incorrectFeedback: string;
  /** The deep explanation: grammar, meaning, translation, common mistakes. */
  comprehensiveFeedback?: string;
}

export interface Activity extends ActivityFeedback {
  id: string;
  type: ActivityType;
  timestamp: number;
  title: string;
  emoji: string;
  color: ActivityColor;
  points: number;
  difficulty: Difficulty;
  /** Block progress until the learner answers. */
  requiredForNext: boolean;
  /** How the video behaves when the activity fires. */
  onReach: "pause" | "continue";
  durationHintSeconds?: number;
  content: ActivityContent;
  lessonContent?: {
    warmUp?: string;
    form?: string;
    meaning?: string;
    use?: string;
    personalizedExamples?: string[];
    lifeApplication?: string;
  };
  audioText?: string;
  catFeedback?: { correct?: string; incorrect?: string };
}

export interface Segment {
  id: string;
  title: string;
  startTime: number;
  endTime: number;
  summary?: string;
  focus?: { grammar?: string[]; vocabulary?: string[]; pronunciation?: string[] };
  activities: Activity[];
}

export interface Badge {
  id: string;
  name: string;
  emoji: string;
  rarity: "common" | "rare" | "epic" | "legendary";
  condition: string;
  description: string;
}

export interface LearnerProfile {
  name: string;
  level: string;
  nativeLanguage: string;
  goals: string;
  interests: string;
  facts: string;
}

export interface Lesson {
  schemaVersion?: string;
  metadata: {
    title: string;
    targetLanguage: string;
    cefrLevel: string;
    estimatedDurationSeconds: number;
    videoUrl?: string;
    posterUrl?: string;
    learnerL1?: string;
    /** Flix addition: which episode this lesson belongs to. */
    episodeId?: string;
  };
  segments: Segment[];
  globalSettings: {
    pointsToLevelUp: number;
    enableStreak: boolean;
    suspenseSounds: boolean;
    activitiesPerSegment?: number;
  };
  badges: Badge[];
  learnerProfile?: LearnerProfile;
  /** Flix addition: quality report produced by the validator. */
  quality?: LessonQualityReport;
}

export interface LessonQualityReport {
  ok: boolean;
  errors: string[];
  warnings: string[];
  activityCount: number;
  segmentCount: number;
  byType: Partial<Record<ActivityType, number>>;
  missingTypes: ActivityType[];
  hardCount: number;
  averagePoints: number;
  score: number;
}

/* ─────────────────────────── WATCH PARTY ──────────────────────────── */

export type PartyMode = "host" | "follow" | "independent";

export interface PartyRoomState {
  roomId: string;
  episodeId: string;
  hostUserId: string;
  isPlaying: boolean;
  currentTime: number;
  playbackRate: number;
  subtitleTrack: string | null;
  subtitleMode: SubtitleMode;
  /** Server (room) clock at the moment this state was published. */
  serverTimestamp: number;
}

export interface PartyParticipant {
  id: string;
  name: string;
  isHost: boolean;
  isCoHost: boolean;
  joinedAt: number;
  /** Last reported playback position, for "who is ahead" UI. */
  drift?: number;
}

export interface PartyMessage {
  type: "state" | "participant" | "activity" | "chat";
  from: string;
  at: number;
  payload: unknown;
}

export interface ProgressRecord {
  episodeId: string;
  lessonId?: string;
  positionSeconds: number;
  completedActivityIds: string[];
  xp: number;
  segmentIndex: number;
  updatedAt: number;
}
