// ── Timer Ring ──
const TimerRing: React.FC<{
  timeLeft: number; total: number; size?: number; colorClass?: string;
}> = ({ timeLeft, total, size = 80 }) => {
  const radius = (size - 8) / 2;
  const circumference = 2 * Math.PI * radius;
  const progress = total > 0 ? timeLeft / total : 0;
  const offset = circumference * (1 - progress);
  const isWarning = progress < 0.3;
  const isDanger = progress < 0.15;

  return (
    <div className="relative flex items-center justify-center" style={{ width: size, height: size }}>
      <svg width={size} height={size} className="timer-ring">
        <circle cx={size / 2} cy={size / 2} r={radius} fill="none"
          stroke="rgba(201,168,76,0.15)" strokeWidth="6" />
        <circle cx={size / 2} cy={size / 2} r={radius} fill="none"
          stroke={isDanger ? '#ef4444' : isWarning ? '#f59e0b' : '#c9a84c'}
          strokeWidth="6" strokeDasharray={circumference}
          strokeDashoffset={offset}
          strokeLinecap="round"
          className={`timer-ring-progress ${isDanger ? 'animate-heartbeat' : ''}`}
          style={{ filter: isDanger ? 'drop-shadow(0 0 6px #ef4444)' : '' }} />
      </svg>
      <div className={`absolute font-cinzel font-bold text-center ${isDanger ? 'text-red-500' : 'text-amber-700'}`}
        style={{ fontSize: size * 0.22 }}>
        {formatTime(timeLeft)}
      </div>
    </div>
  );
};

