function copyStylesToPopup(sourceDoc: Document, targetDoc: Document) {
  // Copy <style> and <link> nodes (no scripts) so the popup looks identical.
  const headEls = Array.from(sourceDoc.head.querySelectorAll('style, link, meta'))
    .filter((el) => {
      const tag = el.tagName.toLowerCase();
      if (tag === 'style') return true;
      if (tag === 'meta') {
        const name = (el as HTMLMetaElement).name;
        const charset = (el as HTMLMetaElement).getAttribute('charset');
        return name === 'viewport' || !!charset;
      }
      if (tag === 'link') {
        const rel = (el as HTMLLinkElement).rel;
        return rel === 'stylesheet' || rel === 'preconnect' || rel === 'dns-prefetch';
      }
      return false;
    });

  // Clean head first
  targetDoc.head.innerHTML = '';
  headEls.forEach((el) => targetDoc.head.appendChild(el.cloneNode(true)));
}

const PopupPortal: React.FC<{
  win: Window;
  title: string;
  onClose: () => void;
  children: React.ReactNode;
}> = ({ win, title, onClose, children }) => {
  const [container, setContainer] = useState<HTMLDivElement | null>(null);

  useEffect(() => {
    const doc = win.document;
    doc.title = title;
    doc.body.style.margin = '0';
    doc.body.style.background = '#000';

    copyStylesToPopup(window.document, doc);

    const el = doc.createElement('div');
    el.id = 'student-root';
    doc.body.appendChild(el);
    setContainer(el);

    const tick = window.setInterval(() => {
      if (win.closed) {
        window.clearInterval(tick);
        onClose();
      }
    }, 500);

    return () => {
      window.clearInterval(tick);
      try {
        el.remove();
      } catch { }
    };
  }, [win, title, onClose]);

  if (!container) return null;
  return createPortal(children, container);
};

