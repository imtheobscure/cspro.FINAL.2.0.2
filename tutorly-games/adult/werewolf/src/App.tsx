function formatTime(seconds: number): string {
  const m = Math.floor(seconds / 60);
  const s = seconds % 60;
  return `${m}:${s.toString().padStart(2, '0')}`;
}



function generateNarration(phase: Phase, round: number, players: Player[]): string {
  const alive = players.filter(p => !p.isEliminated);
  if (phase === 'night') {
    return `Night ${round} falls upon the village. ${alive.length} souls remain. The darkness hides many secrets. Special roles, wake and act in silence…`;
  }
  if (phase === 'day') {
    return `Dawn breaks over the village. The townspeople gather in the square, fear etched on every face. It is time to discuss and find the wolves among you.`;
  }
  if (phase === 'voting') {
    return `The debate is over. It is time to vote. Raise your hand or speak your accusation. The majority will decide who faces elimination today.`;
  }
  return '';
}

