type Phase = 'setup' | 'night' | 'day' | 'voting' | 'result' | 'gameover';
type Team = 'village' | 'werewolf' | 'neutral';
type PlayerStatus = 'alive' | 'eliminated' | 'protected' | 'suspected' | 'revealed' | 'loved';

export interface RoleDef {
  id: string;
  name: string;
  emoji: string;
  team: Team;
  description: string;
  ability: string;
  requiredPhrases?: string[];
  nightAction?: boolean;
  cssClass?: string;
}

export interface Player {
  id: string;
  name: string;
  /** Emoji or short text avatar (teacher/learner editable) */
  avatar: string;
  role: RoleDef;
  status: PlayerStatus;
  isActor: boolean;
  isEliminated: boolean;
  votes: number;

  /** 0–10. Higher = more “lucky” in optional luck checks. */
  luckRate: number;

  /** Optional per-player voice for browser read-aloud (teacher chooses; varies by device). */
  voiceName?: string;
  /** Optional hint coming from AI JSON (e.g., "female UK calm", "male US gritty"). */
  voiceStyle?: string;

  facts?: string;
  traits?: string[];
  cefrLevel?: string;
  savedBy?: string;
  accusedBy?: string[];
  lastDefense?: string;
  isLoved?: boolean;
  partnerId?: string;
}

interface LogEntry {
  id: string;
  text: string;
  type: 'night' | 'day' | 'death' | 'save' | 'vote' | 'system' | 'speak';
  timestamp: Date;
  icon?: string;
}

export interface GameContent {
  schemaVersion?: string;
  gameName?: string;
  setting?: string;
  stakes?: string;
  targetLanguage?: string;
  cefrLevel?: string;

  teacherNotes?: {
    speakingGoal?: string;
    focusSkills?: string[];
    rulesForLearners?: string[];
    teacherShortcuts?: string[];
  };

  host?: {
    voiceStyle?: string;
    intro?: string[];
    phaseLines?: Partial<Record<
      'nightStart' | 'werewolves' | 'seer' | 'doctor' | 'dayStart' | 'votingStart' | 'execution' | 'villageWin' | 'werewolvesWin',
      string[]
    >>;
    recapTemplates?: string[];
  };

  /** Actor/NPC language library generated by AI */
  aiLines?: {
    actorGlobal?: {
      accuse?: string[];
      defend?: string[];
      misdirection?: string[];
      trustBuilding?: string[];
    };
    perPlayer?: Record<string, {
      accuse?: string[];
      defend?: string[];
      alibiNight?: string[];
      emotionalPleas?: string[];
      trustBuilding?: string[];
    }>;
  };

  /** Optional narrative system */
  scenarios?: Array<{
    id: string;
    title: string;
    description: string;
    triggerPhase?: Phase | 'any';
    hostLines?: string[];
    studentPrompt?: string;
    luckCheck?: {
      mode: 'perPlayer' | 'targetOnly' | 'party';
      thresholdHint?: string;
    };
    branches?: Array<{
      id: string;
      if: string;
      hostLines?: string[];
      studentPrompt?: string;
    }>;
  }>;

  /** Luck mechanic rules as text (teacher-facing) */
  luckRules?: {
    explanation?: string;
    examples?: string[];
  };

  discussionTopics?: string[];
  requiredPhrases?: Record<string, string[]>;
}

