class SoundEngine {
  private sounds: Record<string, HTMLAudioElement> = {};
  private settings: SoundSettings;
  private ambientRef: HTMLAudioElement | null = null;
  private musicRef: HTMLAudioElement | null = null;

  constructor(settings: SoundSettings) {
    this.settings = settings;
  }

  updateSettings(settings: SoundSettings) {
    this.settings = settings;
    if (this.ambientRef) this.ambientRef.volume = settings.volume * 0.28;
    if (this.musicRef) this.musicRef.volume = settings.volume * 0.22;
  }

  private getOrCreate(key: string, url: string): HTMLAudioElement {
    if (!this.sounds[key]) {
      const audio = new Audio(url);
      audio.volume = this.settings.volume;
      audio.crossOrigin = 'anonymous';
      this.sounds[key] = audio;
    }
    return this.sounds[key];
  }

  play(key: keyof SoundSettings) {
    if (key === 'volume') return;
    try {
      const val = this.settings[key];
      if (typeof val !== 'string' || !val) return;
      const audio = this.getOrCreate(String(key), val);
      audio.volume = this.settings.volume;
      audio.currentTime = 0;
      audio.play().catch(() => {});
    } catch (e) {}
  }

  startAmbient(type: 'night' | 'day') {
    this.stopAmbient();
    this.startMusic(type);
    try {
      const url = type === 'night' ? this.settings.ambientNightUrl : this.settings.ambientDayUrl;
      if (!url) return;
      const audio = new Audio(url);
      audio.volume = this.settings.volume * 0.28;
      audio.loop = true;
      audio.crossOrigin = 'anonymous';
      audio.play().catch(() => {});
      this.ambientRef = audio;
    } catch (e) {}
  }

  startMusic(type: 'night' | 'day') {
    this.stopMusic();
    if (!this.settings.musicEnabled) return;
    try {
      const url = type === 'night' ? this.settings.musicNightUrl : this.settings.musicDayUrl;
      if (!url) return;
      const audio = new Audio(url);
      audio.volume = this.settings.volume * 0.22;
      audio.loop = true;
      audio.crossOrigin = 'anonymous';
      audio.play().catch(() => {});
      this.musicRef = audio;
    } catch (e) {}
  }

  stopAmbient() {
    if (this.ambientRef) {
      this.ambientRef.pause();
      this.ambientRef = null;
    }
  }

  stopMusic() {
    if (this.musicRef) {
      this.musicRef.pause();
      this.musicRef = null;
    }
  }

  stopAll() {
    Object.values(this.sounds).forEach(a => { a.pause(); a.currentTime = 0; });
    this.stopAmbient();
    this.stopMusic();
  }
}

