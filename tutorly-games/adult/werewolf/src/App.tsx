/**
 * The werewolf engine. It runs headless of onboarding: `initial` is the seed the
 * shared Tutorly splash/setup flow produced, and the default export below wires
 * that flow in front of it.
 */
function WerewolfStudio({
  initial,
  onRestart,
}: {
  initial?: WerewolfSeed;
  onRestart?: () => void;
} = {}) {
  const [gamePhase, setGamePhase] = useState<'splash' | 'setup' | 'playing' | 'gameover'>(
    initial ? 'playing' : 'splash',
  );
  const [darkMode, setDarkMode] = useState(false);
  const [studentWin, setStudentWin] = useState<Window | null>(null);
  const [showSettings, setShowSettings] = useState(false);
  const [soundSettings, setSoundSettings] = useState<SoundSettings>(DEFAULT_SOUND_SETTINGS);
  const [selectedVoice, setSelectedVoice] = useState('');
  const [voices, setVoices] = useState<SpeechSynthesisVoice[]>([]);
  const [toasts, setToasts] = useState<Toast[]>([]);
  const [logs, setLogs] = useState<LogEntry[]>([]);
  const [activePrompt, setActivePrompt] = useState('');
  const [game, setGame] = useState<GameConfig>({
    players: initial?.players ?? [],
    roles: DEFAULT_ROLES,
    phase: 'setup',
    round: 1,
    nightActions: {},
    discussionTimeLeft: 300,
    voteTimeLeft: 180,
    isTimerRunning: false,
    isNightActionDone: {},
    content: initial?.content,
  });

  // A seed means the shared setup page already chose players, roles and the AI
  // pack — say so in the log so the Game Master knows what they are looking at.
  useEffect(() => {
    if (!initial) return;
    addLog(
      `🎮 Game initialized from the Tutorly setup page — ${initial.players.length} players` +
        (initial.content ? ', AI narration pack loaded.' : ', no AI pack (built-in narration).'),
      'system',
      '🎮',
    );
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const soundEngineRef = useRef<SoundEngine>(new SoundEngine(DEFAULT_SOUND_SETTINGS));
  const speechEngineRef = useRef<SpeechEngine>(new SpeechEngine());

  // Load voices
  useEffect(() => {
    const loadVoices = () => {
      const v = speechEngineRef.current.getVoices();
      setVoices(v);
    };
    loadVoices();
    window.speechSynthesis?.addEventListener('voiceschanged', loadVoices);
    return () => window.speechSynthesis?.removeEventListener('voiceschanged', loadVoices);
  }, []);

  // Update sound engine when settings change
  useEffect(() => {
    soundEngineRef.current.updateSettings(soundSettings);
  }, [soundSettings]);

  // Dark mode class
  useEffect(() => {
    document.documentElement.classList.toggle('dark', darkMode);
  }, [darkMode]);

  const addToast = useCallback((message: string, type: Toast['type'], icon?: string) => {
    const id = genId();
    setToasts(prev => [...prev, { id, message, type, icon }]);
    setTimeout(() => setToasts(prev => prev.filter(t => t.id !== id)), 4000);
  }, []);

  const removeToast = useCallback((id: string) => {
    setToasts(prev => prev.filter(t => t.id !== id));
  }, []);

  const addLog = useCallback((text: string, type: LogEntry['type'], icon?: string) => {
    const entry: LogEntry = { id: genId(), text, type, timestamp: new Date(), icon };
    setLogs(prev => [...prev, entry]);
  }, []);

  const handleGameStart = useCallback((players: Player[], roles: RoleDef[], content?: GameContent) => {
    setGame(prev => ({
      ...prev,
      players,
      roles,
      content,
      phase: 'setup',
      round: 1,
      nightActions: {},
      discussionTimeLeft: 300,
      voteTimeLeft: 180,
      isTimerRunning: false,
      isNightActionDone: {},
      winCondition: null,
    }));
    setLogs([]);
    addLog('🎮 Game initialized! The village of mystery awaits…', 'system', '🎮');
    setGamePhase('playing');
    addToast('🎮 Game started! Good luck, Game Master!', 'success', '🎮');
  }, [addLog, addToast]);

  const handleGameUpdate = useCallback((updates: Partial<GameConfig>) => {
    setGame(prev => ({ ...prev, ...updates }));
    if (updates.phase === 'gameover') {
      setTimeout(() => setGamePhase('gameover'), 500);
    }
  }, []);

  const closeStudentWindow = useCallback(() => {
    try {
      studentWin?.close();
    } catch { }
    setStudentWin(null);
  }, [studentWin]);

  const openStudentWindow = useCallback(() => {
    // Must be called from a user gesture (button click) to avoid popup blockers.
    const w = window.open('', 'WerewolfStudentScreen', 'popup=yes,width=1280,height=720');
    if (!w) {
      addToast('Popup blocked by the browser. Please allow popups for this site.', 'error', '🚫');
      return;
    }
    setStudentWin(w);
    try {
      w.focus();
    } catch { }
  }, [addToast]);

  const handleReset = useCallback(() => {
    soundEngineRef.current.stopAll();
    speechEngineRef.current.stop();
    closeStudentWindow();

    // Launched from the shared Tutorly setup page: hand control back to it
    // instead of dropping the class into the game's own advanced screen.
    if (onRestart) {
      onRestart();
      return;
    }
    setGamePhase('setup');
    setLogs([]);
    setActivePrompt('');
    setGame(prev => ({ ...prev, phase: 'setup', round: 1, players: [] }));
  }, [closeStudentWindow, onRestart]);

  // Splash screen
  if (gamePhase === 'splash') {
    return (
      <div className="min-h-screen night-sky flex flex-col items-center justify-center relative overflow-hidden">
        <StarsBackground count={120} />
        <div className="fog-layer" />

        {/* Moon */}
        <div className="absolute top-12 right-24 moon-glow animate-float z-10"
          style={{ width: 100, height: 100, borderRadius: '50%',
            background: 'radial-gradient(circle at 35% 35%, #f5f5dc, #d4c875, #b8a830)' }} />

        {/* Village Silhouette */}
        <div className="village-silhouette absolute bottom-0 left-0 right-0 h-40 z-10 pointer-events-none" />

        <div className="relative z-20 text-center px-4">
          <div className="animate-float inline-block mb-4">
            <span style={{ fontSize: '100px', filter: 'drop-shadow(0 0 30px rgba(139,26,26,0.8))' }}>🐺</span>
          </div>

          <h1 className="font-cinzel-deco text-6xl md:text-8xl font-black text-white text-glow-gold mb-2">
            WEREWOLF
          </h1>
          <div className="divider-gold text-2xl text-amber-400 max-w-md mx-auto mb-2">
            <span>✦</span>
          </div>
          <p className="font-spectral text-2xl text-amber-200 mb-2 italic">
            Educational Language Game
          </p>
          <p className="font-cinzel text-amber-400 text-lg mb-10 tracking-widest">
            TEACHER GAME MASTER EDITION
          </p>

          <div className="flex flex-col sm:flex-row gap-4 justify-center">
            <button
              onClick={() => setGamePhase('setup')}
              className="btn-gold px-10 py-5 rounded-2xl text-2xl font-cinzel-deco font-black shadow-2xl hover:scale-105 transition-all animate-pulse-gold">
              🎮 BEGIN GAME
            </button>
            <button
              onClick={() => setShowSettings(true)}
              className="btn-night px-8 py-5 rounded-2xl text-xl font-cinzel font-bold shadow-2xl hover:scale-105 transition-all">
              ⚙️ Settings
            </button>
          </div>

          {/* Feature Pills */}
          <div className="mt-12 flex flex-wrap justify-center gap-3">
            {[
              '🏫 6–20 Players', '🎭 10 Unique Roles', '📋 JSON Import',
              '🎙️ AI Host Narration', '💬 Speaking Prompts', '📊 CEFR Levels',
            ].map(f => (
              <span key={f} className="px-4 py-2 rounded-full bg-white/10 text-amber-200 font-spectral text-sm border border-white/20 backdrop-blur-sm">
                {f}
              </span>
            ))}
          </div>
        </div>

        {showSettings && (
          <SettingsModal
            settings={soundSettings}
            onSave={setSoundSettings}
            onClose={() => setShowSettings(false)}
            voices={voices}
            selectedVoice={selectedVoice}
            onVoiceChange={setSelectedVoice}
            darkMode={darkMode}
            onDarkModeToggle={() => setDarkMode(d => !d)}
          />
        )}

        <ToastNotification toasts={toasts} removeToast={removeToast} />
      </div>
    );
  }

  if (gamePhase === 'setup') {
    return (
      <>
        <SetupScreen
          onStart={handleGameStart}
          roles={DEFAULT_ROLES}
        />
        {showSettings && (
          <SettingsModal
            settings={soundSettings}
            onSave={setSoundSettings}
            onClose={() => setShowSettings(false)}
            voices={voices}
            selectedVoice={selectedVoice}
            onVoiceChange={setSelectedVoice}
            darkMode={darkMode}
            onDarkModeToggle={() => setDarkMode(d => !d)}
          />
        )}
        <div className="fixed top-4 right-4 z-50">
          <button onClick={() => setShowSettings(true)}
            className="btn-gold px-4 py-2 rounded-xl text-sm flex items-center gap-2">
            ⚙️ Settings
          </button>
        </div>
        <ToastNotification toasts={toasts} removeToast={removeToast} />
      </>
    );
  }

  if (gamePhase === 'gameover') {
    return (
      <>
        <GameOverScreen
          game={game}
          onPlayAgain={handleReset}
          darkMode={darkMode}
        />
        <ToastNotification toasts={toasts} removeToast={removeToast} />
      </>
    );
  }

  return (
    <>
      <ControlRoom
        game={game}
        onGameUpdate={handleGameUpdate}
        roles={DEFAULT_ROLES}
        logs={logs}
        addLog={addLog}
        soundEngine={soundEngineRef.current}
        speechEngine={speechEngineRef.current}
        selectedVoice={selectedVoice}
        onShowStudentDisplay={openStudentWindow}
        onReset={handleReset}
        addToast={addToast}
        onActivePromptChange={setActivePrompt}
      />

      {/* Settings Gear — inline position for the same reason as the shell's gear:
          the game's unlayered CSS outranks Tailwind's @layer utilities, so the
          `fixed` class loses and the button ends up in the document flow. */}
      <button
        onClick={() => setShowSettings(true)}
        style={{
          position: 'fixed',
          right: 16,
          bottom: 16,
          zIndex: 60,
          width: 48,
          height: 48,
          borderRadius: '50%',
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'center',
          fontSize: '1.25rem',
          boxShadow: '0 10px 30px rgba(0,0,0,0.28)',
        }}
        className="btn-gold">
        ⚙️
      </button>

      {/* Student Display: real popup window (share this screen) */}
      {studentWin && (
        <PopupPortal win={studentWin} title="🐺 Werewolf – Student Screen" onClose={closeStudentWindow}>
          <StudentDisplay
            game={game}
            onClose={closeStudentWindow}
            activePrompt={activePrompt}
            media={{ nightSceneUrl: soundSettings.nightSceneUrl, daySceneUrl: soundSettings.daySceneUrl }}
          />
        </PopupPortal>
      )}

      {/* Settings Modal */}
      {showSettings && (
        <SettingsModal
          settings={soundSettings}
          onSave={setSoundSettings}
          onClose={() => setShowSettings(false)}
          voices={voices}
          selectedVoice={selectedVoice}
          onVoiceChange={setSelectedVoice}
          darkMode={darkMode}
          onDarkModeToggle={() => setDarkMode(d => !d)}
        />
      )}

      <ToastNotification toasts={toasts} removeToast={removeToast} />
    </>
  );
}

