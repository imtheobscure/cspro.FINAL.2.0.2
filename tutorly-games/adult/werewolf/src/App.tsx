class SpeechEngine {
  private synth = window.speechSynthesis;
  private voices: SpeechSynthesisVoice[] = [];
  private isPaused = false;


  constructor() {
    this.loadVoices();
    this.synth.addEventListener('voiceschanged', () => this.loadVoices());
  }

  private loadVoices() {
    this.voices = this.synth.getVoices();
  }

  getVoices(): SpeechSynthesisVoice[] {
    return this.voices;
  }

  speak(text: string, voiceName?: string, rate = 0.85, pitch = 0.9) {
    this.stop();
    const utter = new SpeechSynthesisUtterance(text);
    if (voiceName) {
      const voice = this.voices.find(v => v.name === voiceName);
      if (voice) utter.voice = voice;
    } else {
      const englishVoice = this.voices.find(v =>
        v.lang.startsWith('en') && (v.name.includes('UK') || v.name.includes('British') || v.name.includes('Daniel') || v.name.includes('Male'))
      ) || this.voices.find(v => v.lang.startsWith('en'));
      if (englishVoice) utter.voice = englishVoice;
    }
    utter.rate = rate;
    utter.pitch = pitch;
    utter.volume = 1;
    this.isPaused = false;
    this.synth.speak(utter);
  }

  pause() {
    if (this.synth.speaking && !this.isPaused) {
      this.synth.pause();
      this.isPaused = true;
    }
  }

  resume() {
    if (this.isPaused) {
      this.synth.resume();
      this.isPaused = false;
    }
  }

  stop() {
    this.synth.cancel();
    this.isPaused = false;
  }

  get speaking() { return this.synth.speaking; }
  get paused() { return this.isPaused; }
}

