#!/usr/bin/env node
/**
 * Write `src/lib/imageManifest.ts` — which artwork files actually exist.
 *
 * The mapping is `path/under/images/without-extension` → the real file (with its
 * extension), so a portrait can be named the way the ORIGINAL app named it,
 * `characters/01.jpg`, or the plain `characters/1.jpg` this app ships, and either
 * one resolves. Keys are canonicalised (`characters/01` and `characters/1` are the
 * same character) and, when a name exists in both forms, the zero-padded original
 * wins — so dropping your own `01.jpg` … `24.jpg` over the shipped set just works.
 *
 * `art.ts` prefers a real picture (a portrait in `public/images/characters/`, the
 * dashboard hero art) and falls back to the generated `.svg` illustration. Without
 * knowing what is on disk, the browser would discover that by trying: five
 * extensions across twenty-five images is a hundred failed requests before the
 * dashboard paints.
 *
 * So the build looks once and records what is here. Runs from `npm run build`
 * before `next build`, so dropping new portraits in and rebuilding is all it
 * takes. Never edit the generated file by hand.
 *
 * Usage: node scripts/manifest-images.mjs
 */
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const imagesDir = path.join(root, "public", "images");
const outFile = path.join(root, "src", "lib", "imageManifest.ts");

/** Raster extensions that count as real artwork, in preference order. */
const EXTENSIONS = ["jpg", "jpeg", "png", "webp", "avif"];

/** Keys are paths under `images/` with no extension: `characters/7`, `tutorly-hero`. */
const found = {};

/**
 * Which of two files claiming the same key wins: a better extension, then the
 * original app's zero-padded name, so `01.jpg` beats `1.jpg`.
 */
const preference = (file) => {
  const ext = path.extname(file).slice(1).toLowerCase();
  const stem = path.basename(file, path.extname(file));
  return EXTENSIONS.indexOf(ext) * 10 + (/^0\d+$/.test(stem) ? 0 : 1);
};

async function scan(dir, prefix = "") {
  let entries = [];
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    if (entry.isDirectory()) {
      await scan(path.join(dir, entry.name), `${prefix}${entry.name}/`);
      continue;
    }
    const ext = path.extname(entry.name).slice(1).toLowerCase();
    if (!EXTENSIONS.includes(ext)) continue;
    const stem = path.basename(entry.name, path.extname(entry.name));
    const canonical = /^\d+$/.test(stem) ? String(Number(stem)) : stem;
    const key = `${prefix}${canonical}`;
    const file = `${prefix}${entry.name}`;
    // Preference wins, so a stray .png copy can never shadow the .jpg.
    if (!found[key] || preference(file) < preference(found[key])) found[key] = file;
  }
}

await scan(imagesDir);

const names = Object.keys(found).sort();
const body = `/**
 * GENERATED by scripts/manifest-images.mjs — do not edit.
 *
 * The real artwork found in \`public/images/\` at build time, as
 * \`path/under/images/without-extension\` → the file that exists (with extension).
 * Regenerate with \`npm run build\` (or \`node scripts/manifest-images.mjs\`).
 */
export const IMAGE_MANIFEST: Record<string, string> = ${JSON.stringify(found, null, 2)};
`;

await writeFile(outFile, body, "utf8");
console.log(
  `[manifest-images] ${names.length} artwork file(s) found${names.length ? `: ${names.slice(0, 6).map((name) => found[name]).join(", ")}${names.length > 6 ? ", …" : ""}` : ""}`,
);
console.log(
  names.length
    ? `[manifest-images] wrote ${path.relative(root, outFile)}`
    : "[manifest-images] wrote an empty manifest — every portrait will use its generated .svg",
);
