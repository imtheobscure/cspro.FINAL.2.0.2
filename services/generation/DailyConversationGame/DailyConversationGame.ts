
import { GoogleGenAI, Modality, Type } from "@google/genai";
import { ai, getProfileContext, generateContentWithRetry } from '../core';
import { ALL_VOICES } from '../../../utils/voices';
import type { LearnerProfile } from '../../../types';
import { useAppStore } from '../../../store/useAppStore';

export const generateConversationGameHtml = (gameData: any, theme: string, profile: any, appStoreContext: any, audioDataMap: Record<string, string> = {}): string => {
    return `
    <!DOCTYPE html>
    <html lang="en">
    <head>
        <meta charset="UTF-8">
        <meta name="viewport" content="width=device-width, initial-scale=1.0">
        <title>Daily Conversation: ${theme}</title>
        
        <style>
            body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; display: flex; justify-content: center; align-items: center; min-height: 100vh; background-color: #f0f4f8; margin: 0; padding: 1rem; }
            .game-container { background-color: white; border-radius: 16px; box-shadow: 0 8px 30px rgba(0,0,0,0.12); padding: 2rem; width: 90%; max-width: 600px; text-align: center; }
            .character-display { margin-bottom: 1.5rem; min-height: 120px; display: flex; flex-direction: column; justify-content: center; align-items: center; }
            .character-emoji { font-size: 5rem; line-height: 1; }
            .status-text { color: #4b5563; font-weight: 500; min-height: 24px; transition: color 0.3s; margin-top: 10px; }
            .intro-text { color: #374151; font-style: italic; background-color: #f3f4f6; padding: 1rem; border-radius: 8px; margin-bottom: 1rem; font-size: 0.95rem; line-height: 1.5; }
            #start-btn { background-color: #4f46e5; color: white; border: none; padding: 1rem 2rem; font-size: 1.2rem; font-weight: 600; border-radius: 8px; cursor: pointer; }
            .choices-container { display: flex; flex-direction: column; gap: 0.75rem; min-height: 150px; margin-top: 1rem; }
            .choice-btn { background-color: #eef2ff; color: #3730a3; border: 2px solid #c7d2fe; padding: 1rem; border-radius: 8px; font-size: 1rem; font-weight: 600; cursor: pointer; text-align: left; transition: all 0.2s; }
            .choice-btn:hover { background-color: #c7d2fe; border-color: #818cf8; }
            .choice-btn:disabled { opacity: 0.5; cursor: not-allowed; }
            #results-container { text-align: left; margin-top: 1.5rem; display: none; }
            #transcript-container { background-color: #f9fafb; border: 1px solid #e5e7eb; border-radius: 8px; padding: 1rem; max-height: 300px; overflow-y: auto; margin-bottom: 1.5rem; }
            .transcript-line { margin-bottom: 0.5rem; }
            .transcript-line b { color: #4f46e5; }
            
            /* Keyword Highlighting */
            .keyword { font-weight: bold; color: #1d4ed8; border-bottom: 2px dotted #93c5fd; cursor: help; position: relative; }
            .keyword .tooltip { visibility: hidden; width: 200px; background-color: #1f2937; color: #fff; text-align: center; border-radius: 6px; padding: 5px; position: absolute; z-index: 100; bottom: 125%; left: 50%; margin-left: -100px; opacity: 0; transition: opacity 0.3s; font-size: 0.85rem; font-weight: normal; }
            .keyword:hover .tooltip { visibility: visible; opacity: 1; }
            
            #discussion-questions h3 { margin-top: 0; }
            #discussion-questions ul { list-style-type: none; padding-left: 0; }
            #discussion-questions li { margin-bottom: 0.75rem; background: #fff; padding: 0.75rem; border-radius: 6px; border: 1px solid #e5e7eb; }
            footer { text-align: center; margin-top: 1rem; font-size: 0.8rem; color: #6b7280; }
        </style>
    </head>
    <body>
        <div class="game-container">
            <div class="character-display">
                <div class="character-emoji" id="character-emoji-display">🎭</div>
                <div id="intro-container" class="intro-text">${gameData.introduction}</div>
                <p class="status-text" id="status-text"></p>
            </div>
            <div class="controls">
                <button id="start-btn"><i class="fas fa-play"></i> Start Game</button>
            </div>
            <div class="choices-container" id="choices-container"></div>
            <div id="results-container"></div>
             <footer>
                <p>Generated by ${appStoreContext.appName}: Top Tutors and Tutorials</p>
                <p>${appStoreContext.appAddress}</p>
                <p>Generated for: ${profile.name}</p>
            </footer>
        </div>
       
        <script>
            const gameData = ${JSON.stringify(gameData)};
            const audioDataMap = ${JSON.stringify(audioDataMap)};

            const startBtn = document.getElementById('start-btn');
            const statusText = document.getElementById('status-text');
            const choicesContainer = document.getElementById('choices-container');
            const emojiDisplay = document.getElementById('character-emoji-display');
            const introContainer = document.getElementById('intro-container');
            const resultsContainer = document.getElementById('results-container');

            let audioQueue = [];
            let currentAudioContext = null;
            let conversationPath = [];

            function decode(base64) {
              const binaryString = atob(base64);
              const len = binaryString.length;
              const bytes = new Uint8Array(len);
              for (let i = 0; i < len; i++) { bytes[i] = binaryString.charCodeAt(i); }
              return bytes;
            }

            async function playAudioFromBase64(base64) {
                if (currentAudioContext) await currentAudioContext.close();
                currentAudioContext = new (window.AudioContext || window.webkitAudioContext)({ sampleRate: 24000 });
                
                const data = decode(base64);
                const dataInt16 = new Int16Array(data.buffer);
                const frameCount = dataInt16.length;
                const buffer = currentAudioContext.createBuffer(1, frameCount, 24000);
                const channelData = buffer.getChannelData(0);
                for (let i = 0; i < frameCount; i++) { channelData[i] = dataInt16[i] / 32768.0; }

                return new Promise((resolve, reject) => {
                    const source = currentAudioContext.createBufferSource();
                    source.buffer = buffer;
                    source.connect(currentAudioContext.destination);
                    source.start();
                    source.onended = resolve;
                    source.onerror = reject;
                });
            }

            async function processAudioQueue() {
                if (audioQueue.length === 0) {
                    const currentNode = audioQueue.node;
                    if (currentNode.choices) {
                        renderChoices(currentNode.choices);
                    } else {
                        renderEndScreen(currentNode, audioQueue.isWin);
                    }
                    return;
                }
                const line = audioQueue.shift();
                conversationPath.push(line);
                const character = gameData.characters.find(c => c.name === line.speaker);
                emojiDisplay.textContent = character.emoji;
                statusText.textContent = \`\${line.speaker} is speaking...\`;
                
                const audioKey = \`\${line.speaker}::\${line.line}\`;
                const audioData = audioDataMap[audioKey];

                if (audioData) { 
                    await playAudioFromBase64(audioData); 
                    processAudioQueue();
                } else {
                    // Fallback to Web Speech API
                    const utterance = new SpeechSynthesisUtterance(line.line);
                    const voices = window.speechSynthesis.getVoices();
                    if (character && character.voice) {
                        let matched = voices.find(v => v.name.includes(character.voice) || v.name === character.voice);
                        if (matched) utterance.voice = matched;
                    }
                    utterance.onend = processAudioQueue;
                    utterance.onerror = processAudioQueue;
                    window.speechSynthesis.speak(utterance);
                }
            }
            
            function renderChoices(choices) {
                choicesContainer.innerHTML = '';
                choices.forEach(choice => {
                    const btn = document.createElement('button');
                    btn.className = 'choice-btn';
                    btn.textContent = choice.text;
                    btn.onclick = () => handleChoiceClick(choice.next, choice.text);
                    choicesContainer.appendChild(btn);
                });
                statusText.textContent = 'Your turn to respond...';
                emojiDisplay.textContent = '🤔';
            }

            function renderEndScreen(node, isWin) {
                choicesContainer.innerHTML = '';
                startBtn.style.display = 'none';
                introContainer.style.display = 'none';
                emojiDisplay.style.display = 'none';
                
                let transcriptHTML = conversationPath.map(line => \`<div class="transcript-line"><b>\${line.speaker}:</b> \${line.line}</div>\`).join('');

                if (isWin) {
                    statusText.textContent = 'You found the secret!';
                    statusText.style.color = '#10b981';
                    statusText.style.fontSize = '1.2rem';
                    
                    // Highlight keywords in transcript
                    if (node.keywords) {
                        node.keywords.forEach(kw => {
                            const regex = new RegExp(\`(?![^<]*>)\\\\b(\${kw.word})\\\\b\`, 'gi');
                            transcriptHTML = transcriptHTML.replace(regex, \`<span class="keyword">$1<span class="tooltip">\${kw.definition}</span></span>\`);
                        });
                    }

                    resultsContainer.innerHTML = \`
                        <h2 style="color: #4f46e5;">Conversation Transcript</h2>
                        <div id="transcript-container">\${transcriptHTML}</div>
                        <div id="discussion-questions">
                            <h3>🤔 Reflection Questions</h3>
                            <ul>\${node.discussionQuestions.map(q => \`<li>\${q}</li>\`).join('')}</ul>
                        </div>
                        <p style="text-align:center; font-weight: bold; margin-top: 1rem; font-size: 1.1rem; color: #10b981;">Secret Code: \${gameData.secretCode}</p>
                    \`;
                } else {
                    statusText.textContent = 'Game Over. Refresh to try again!';
                    statusText.style.color = '#ef4444';
                    resultsContainer.innerHTML = \`
                        <h2>Conversation Transcript</h2>
                        <div id="transcript-container">\${transcriptHTML}</div>
                        <p style="text-align:center; font-weight: bold; margin-top: 1rem;">You didn't find the secret this time. Refresh the page to try again!</p>
                    \`;
                }
                resultsContainer.style.display = 'block';
            }

            function handleChoiceClick(nextNodeKey, choiceText) {
                choicesContainer.innerHTML = '';
                conversationPath.push({ speaker: 'You', line: choiceText });
                const nextNode = gameData.game_graph[nextNodeKey];
                
                if (!nextNode) return;
                
                audioQueue = [...nextNode.dialogue];
                audioQueue.node = nextNode;
                audioQueue.isWin = nextNodeKey === 'end_win';
                processAudioQueue();
            }

            startBtn.addEventListener('click', () => {
                startBtn.style.display = 'none';
                introContainer.style.display = 'none';
                conversationPath = [];
                const startNode = gameData.game_graph.start;
                audioQueue = [...startNode.dialogue];
                audioQueue.node = startNode;
                processAudioQueue();
            });
        </script>
    </body>
    </html>`;
};

export const generateConversationGame = async (profile: LearnerProfile, charactersPrompt: string, themePrompt: string): Promise<{htmlContent: string, secretCode: string, theme: string}> => {
    
    // Inject profile info for level adjustment and interests
    const targetLevel = profile.cefrLevel;
    const interests = profile.interests || "General topics";
    
    // If user didn't specify characters, generate them based on interests
    const chars = charactersPrompt.trim() || "Create 2-3 characters based on the learner's interest: " + interests;
    const theme = themePrompt.trim() || "A scenario relevant to: " + interests;

    const maleVoices = ALL_VOICES.filter(v => v.gender === 'male').map(v => v.id);
    const femaleVoices = ALL_VOICES.filter(v => v.gender === 'female').map(v => v.id);

    const dialogueLineSchema = {
        type: Type.OBJECT,
        properties: {
            speaker: { type: Type.STRING },
            line: { type: Type.STRING },
            emotion: { type: Type.STRING, enum: ['cheerful', 'sad', 'angry', 'neutral', 'excited', 'dramatic', 'humorous', 'suspenseful', 'formal', 'casual'] }
        },
        required: ["speaker", "line", "emotion"]
    };

    const choiceSchema = {
        type: Type.OBJECT,
        properties: {
            text: { type: Type.STRING },
            next: { type: Type.STRING, description: "The key of the next node in the game graph (e.g., 'mid_1', 'end_lose_2')." }
        },
        required: ["text", "next"]
    };

    const midNodeSchema = {
        type: Type.OBJECT,
        properties: {
            dialogue: { type: Type.ARRAY, items: dialogueLineSchema },
            choices: { type: Type.ARRAY, items: choiceSchema, minItems: 2, maxItems: 2 }
        },
        required: ["dialogue", "choices"]
    };

    const startNodeSchema = {
        type: Type.OBJECT,
        properties: {
            dialogue: { type: Type.ARRAY, items: dialogueLineSchema },
            choices: { type: Type.ARRAY, items: choiceSchema, minItems: 3, maxItems: 3 }
        },
        required: ["dialogue", "choices"]
    };
    
    const endNodeSchema = {
        type: Type.OBJECT,
        properties: {
            dialogue: { type: Type.ARRAY, items: dialogueLineSchema }
        },
        required: ["dialogue"]
    };

    const winNodeSchema = {
        type: Type.OBJECT,
        properties: {
            dialogue: { type: Type.ARRAY, items: dialogueLineSchema },
            keywords: {
                type: Type.ARRAY,
                items: {
                    type: Type.OBJECT,
                    properties: {
                        word: { type: Type.STRING },
                        definition: { type: Type.STRING }
                    },
                    required: ["word", "definition"]
                }
            },
            discussionQuestions: {
                type: Type.ARRAY,
                items: { type: Type.STRING }
            }
        },
        required: ["dialogue", "keywords", "discussionQuestions"]
    };

    const conversationGameSchema = {
        type: Type.OBJECT,
        properties: {
            secretCode: { type: Type.STRING },
            introduction: { type: Type.STRING, description: "A paragraph introducing the characters and the situation/context of the game." },
            characters: {
                type: Type.ARRAY,
                items: {
                    type: Type.OBJECT,
                    properties: {
                        name: { type: Type.STRING },
                        emoji: { type: Type.STRING },
                        voice: { type: Type.STRING },
                        gender: { type: Type.STRING, enum: ['male', 'female'] },
                        personality: { type: Type.STRING }
                    },
                    required: ["name", "emoji", "voice", "gender", "personality"]
                }
            },
            game_graph: {
                type: Type.OBJECT,
                properties: {
                    start: startNodeSchema,
                    mid_1: midNodeSchema,
                    mid_2: midNodeSchema,
                    mid_3: midNodeSchema,
                    end_lose_1: endNodeSchema,
                    end_lose_2: endNodeSchema,
                    end_lose_3: endNodeSchema,
                    end_lose_4: endNodeSchema,
                    end_lose_5: endNodeSchema,
                    end_win: winNodeSchema
                },
                required: ["start", "mid_1", "mid_2", "mid_3", "end_lose_1", "end_lose_2", "end_lose_3", "end_lose_4", "end_lose_5", "end_win"]
            }
        },
        required: ["secretCode", "introduction", "characters", "game_graph"]
    };

    const prompt = `
    ${getProfileContext(profile)}

    You are an expert game designer and storyteller for English Language Learners. Your task is to generate the complete script for a short, branching, multi-character, voice-only conversation game in a graph-based JSON format. The game must have a clear theme and realistic, emotional dialogue suitable for a learner at level: ${targetLevel}.

    ---INPUTS---
    Characters/Emojis: "${chars}"
    Theme: "${theme}"

    ---CRITICAL & NON-NEGOTIABLE INSTRUCTIONS---
    1.  **Create Characters**: Create 2 or 3 distinct characters. Give each a name, personality, emoji, and gender. One character MUST have a personality quirk where they repeat the secret code phrase naturally in their dialogue multiple times.
    2.  **Introduction**: Write a compelling paragraph introducing the characters and the situation.
    3.  **Assign Voices**: Assign each character a unique voice ID from the provided lists.
        - Male Voices: ${maleVoices.join(', ')}
        - Female Voices: ${femaleVoices.join(', ')}
    4.  **Craft the Branching Story**: The game MUST follow a strict 3 -> 2 branching structure.
        - The \`start\` node must have 3 choices, leading to \`mid_1\`, \`mid_2\`, and \`mid_3\` respectively.
        - Each \`mid\` node must have 2 choices, leading to a final \`end\` node.
        - The path to the \`end_win\` node must be logical but not obvious. The other 5 paths must lead to different losing end nodes (\`end_lose_1\` through \`end_lose_5\`).
    5.  **Write Natural Dialogue (CEFR ${targetLevel})**: The dialogue MUST be written in natural, everyday English strictly at the learner's level. 
        - Use vocabulary and grammar suitable for ${targetLevel}.
        - The characters should sound like real people having a conversation. 
        - For EVERY line of speech, you MUST specify the speaker, the line, and an emotion from the list: cheerful, sad, angry, neutral, excited, dramatic, humorous, suspenseful, formal, casual.
    6.  **Winning Path Content**:
        - The dialogue in the \`end_win\` node MUST reveal the secret code.
        - For the \`end_win\` node, you must also generate:
            *   \`keywords\`: An array of 5-7 key vocabulary words from the entire winning conversation path, along with their simple definitions.
            *   \`discussionQuestions\`: An array of 3-4 thought-provoking, open-ended "What would you do if..." questions addressed to the user in the second person (e.g., 'What would you have done differently in this situation?').

    Output a single JSON object that strictly follows the provided schema. Do not include any other text or markdown.
    `;

    // Retry for JSON generation
    const jsonResult = await generateContentWithRetry({
        model: "gemini-2.5-pro",
        contents: prompt,
        config: { responseMimeType: "application/json", responseSchema: conversationGameSchema }
    });
    
    const gameData = JSON.parse(jsonResult.text);
    const secretCode = gameData.secretCode;

    // --- Generate Individual Audio Clips for Each Line ---
    const allLines = [];
    Object.values(gameData.game_graph).forEach((node: any) => {
        if (node.dialogue) {
            allLines.push(...node.dialogue);
        }
    });

    const audioGenerationPromises = allLines.map(line => {
        const character = gameData.characters.find(c => c.name === line.speaker);
        if (!character) return Promise.resolve(null);
        
        const ttsPrompt = `Say ${line.emotion}: ${line.line}`;
        // Retry for each audio chunk
        return generateContentWithRetry({
            model: "gemini-2.5-flash-preview-tts",
            contents: [{ parts: [{ text: ttsPrompt }] }],
            config: {
                responseModalities: [Modality.AUDIO],
                speechConfig: { voiceConfig: { prebuiltVoiceConfig: { voiceName: character.voice } } }
            }
        });
    });

    const audioResponses = await Promise.all(audioGenerationPromises);

    const audioDataMap: Record<string, string> = {};
    audioResponses.forEach((res, index) => {
        if (!res) return;
        const line = allLines[index];
        const base64Audio = res.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;
        if (base64Audio) {
            const key = `${line.speaker}::${line.line}`; // Unique key for the line
            audioDataMap[key] = base64Audio;
        }
    });

    // --- Generate Final HTML ---
    const htmlContent = generateConversationGameHtml(gameData, theme, profile, {
        appName: useAppStore.getState().appName,
        appAddress: useAppStore.getState().appAddress
    }, audioDataMap);
    
    return { htmlContent, secretCode, theme };
};
