import React from 'react';
import ReactDOM from 'react-dom/client';
import App from './App';
// The Tailwind entry. This MUST be imported from JS, not linked from index.html:
// the original app linked `./index.css` in its HTML, which the bundler never sees,
// so the first build here shipped an unstyled page.
import './index.css';

const rootElement = document.getElementById('root');
if (!rootElement) {
  throw new Error("Could not find root element to mount to");
}

const root = ReactDOM.createRoot(rootElement);
root.render(
  <React.StrictMode>
    <App />
  </React.StrictMode>
);