/**
 * Generate one standalone exam HTML per preset into .check/.
 *
 * Exists because the builder's own validator only checks that the JSON is
 * *parseable* - it never checks the runtime can RENDER the question types in it.
 * Run: npx tsx exam-builder/scripts/gen-all-exams.ts   (from the repo root)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { InternationalTestPreset, INTERNATIONAL_TEST_PRESETS, createMockExamForPreset } from "../src/testCatalog";
import type { LearnerProfile } from "../src/types";

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.resolve(here, "..", ".check");
fs.mkdirSync(outDir, { recursive: true });

const learner: LearnerProfile = {
  name: "Audit Candidate",
  id: "AUDIT-2026-01",
  email: "audit@example.com",
  notes: "Generated by the automated audit harness.",
  context: "Standards conformance audit",
  targetScore: "80%",
  tutorEmail: "examiner@example.org",
  collectCandidateInfo: true,
};

/**
 * The builder emits the standalone file through a Blob + <a download>. There is
 * no DOM here, so the generator is re-run the same way but the string is kept.
 * We import the module's source and re-execute the string-building path by
 * shadowing the download step.
 */
const run = async () => {
  const mod = await import("../src/quizHtmlGenerator");
  // Capture the generated HTML by intercepting the Blob constructor.
  const captured: string[] = [];
  const realBlob = globalThis.Blob;
  class CapturingBlob {
    parts: any[];
    options: any;
    constructor(parts: any[], options: any) {
      this.parts = parts;
      this.options = options;
      captured.push(parts.map((p) => String(p)).join(""));
    }
    get size() {
      return captured[captured.length - 1]?.length ?? 0;
    }
    get type() {
      return this.options?.type ?? "";
    }
  }
  (globalThis as any).Blob = CapturingBlob;
  (globalThis as any).URL.createObjectURL = () => "blob:audit";
  (globalThis as any).URL.revokeObjectURL = () => {};
  const fakeEl = { href: "", download: "", click() {}, style: {} };
  (globalThis as any).document = {
    body: { appendChild() {}, removeChild() {} },
    createElement: () => fakeEl,
  };

  const summary: any[] = [];
  for (const preset of INTERNATIONAL_TEST_PRESETS as InternationalTestPreset[]) {
    captured.length = 0;
    const schema = createMockExamForPreset(preset, learner.tutorEmail);
    mod.handleSaveQuizAsExamHtml(schema, learner);
    const html = captured[0] || "";
    const file = path.join(outDir, `${preset.id}.html`);
    fs.writeFileSync(file, html, "utf8");

    const types = new Set<string>();
    let questions = 0;
    schema.sections.forEach((s) => {
      (s.questions || []).forEach((q) => {
        questions++;
        types.add(q.type);
      });
    });

    summary.push({
      id: preset.id,
      name: preset.name,
      sections: schema.sections.length,
      questions,
      declaredTimerMode: schema.metadata.timerMode,
      declaredMinutes: schema.metadata.timeLimitMinutes,
      hasReadingPassages: schema.sections.some((s) => (s.readingPassages || []).length > 0),
      types: [...types].sort(),
      bytes: html.length,
      file: path.relative(path.resolve(here, "..", ".."), file),
    });
  }
  (globalThis as any).Blob = realBlob;
  fs.writeFileSync(path.join(outDir, "summary.json"), JSON.stringify(summary, null, 2), "utf8");
  console.table(
    summary.map((s) => ({
      id: s.id,
      sections: s.sections,
      questions: s.questions,
      types: s.types.join(","),
      kb: Math.round(s.bytes / 1024),
    })),
  );
  console.log(`\nWrote ${summary.length} exam file(s) to ${path.relative(process.cwd(), outDir)}`);
};

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
